// Reads the raw Apify Google Places scrape and generates a Supabase migration
// that populates business_images.image_path (hotlinked Google CDN URLs) for
// every business we can match by google_place_id, provided it doesn't already
// have a cover image. Re-runnable: the generated SQL is idempotent (NOT EXISTS
// guard) and safe to re-apply if the scrape is ever refreshed.
//
// Usage: node scripts/extract-cover-images.js

const fs = require('fs');
const path = require('path');

const SOURCE_FILE = path.join(__dirname, '..', 'dataset_crawler-google-places_2026-07-27_12-47-48-071.json');

const raw = JSON.parse(fs.readFileSync(SOURCE_FILE, 'utf8'));

// Dedupe by placeId (same approach as transform-apify.js) and pick out records
// with a usable imageUrl.
const seenPlaceIds = new Set();
const rows = [];
const otherHosts = new Map();
let nullImageCount = 0;

for (const rec of raw) {
  if (!rec.placeId || seenPlaceIds.has(rec.placeId)) continue;
  seenPlaceIds.add(rec.placeId);

  if (!rec.imageUrl) {
    nullImageCount++;
    continue;
  }

  let host;
  try {
    host = new URL(rec.imageUrl).hostname;
  } catch {
    continue; // malformed URL, skip
  }

  const ALLOWED_HOSTS = new Set(['lh3.googleusercontent.com', 'streetviewpixels-pa.googleapis.com']);
  if (!ALLOWED_HOSTS.has(host)) {
    otherHosts.set(host, (otherHosts.get(host) || 0) + 1);
    continue; // third-party CDN, not allow-listed in next.config.ts — report, don't insert
  }

  rows.push({ placeId: rec.placeId, imageUrl: rec.imageUrl, title: rec.title || '' });
}

function sqlEscape(str) {
  return String(str).replace(/'/g, "''");
}

const valuesSql = rows
  .map((r) => `  ('${sqlEscape(r.placeId)}', '${sqlEscape(r.imageUrl)}')`)
  .join(',\n');

// Split into chunks so each generated file is small enough to relay through a
// single MCP apply_migration call (~70 rows per chunk, ~15-20KB each).
const CHUNK_SIZE = 70;
const chunks = [];
for (let i = 0; i < rows.length; i += CHUNK_SIZE) chunks.push(rows.slice(i, i + CHUNK_SIZE));

const OUT_DIR = path.join(__dirname, '..', 'supabase', 'migrations');
const writtenFiles = [];

chunks.forEach((chunk, idx) => {
  const chunkValuesSql = chunk
    .map((r) => `  ('${sqlEscape(r.placeId)}', '${sqlEscape(r.imageUrl)}')`)
    .join(',\n');

  const partLabel = `part${idx + 1}of${chunks.length}`;
  const outFile = path.join(OUT_DIR, `016_business_cover_images_${partLabel}.sql`);

  const migrationSql = `-- =============================================================================
-- Kiambu Road Explorer — Migration 016 (${partLabel})
-- Populate business_images with the cover photo each business already had in
-- the original Google Places scrape (dataset_crawler-google-places_2026-07-27).
-- Hotlinks the Google CDN URL directly (no re-hosting) — matched by
-- google_place_id. Skips any business that already has a cover image, and
-- skips businesses with no place-id match (manually-added listings/malls).
-- Split into ${chunks.length} parts purely to keep each file small; apply in order.
-- Generated by scripts/extract-cover-images.js — re-run that script and
-- reapply if the scrape is ever refreshed.
-- =============================================================================

INSERT INTO business_images (business_id, image_path, is_cover, sort_order, alt_text)
SELECT b.id, v.image_url, true, 0, b.name
FROM businesses b
JOIN (VALUES
${chunkValuesSql}
) AS v(place_id, image_url) ON b.google_place_id = v.place_id
WHERE NOT EXISTS (
  SELECT 1 FROM business_images bi WHERE bi.business_id = b.id AND bi.is_cover = true
);
`;

  fs.writeFileSync(outFile, migrationSql, 'utf8');
  writtenFiles.push(outFile);
});

console.log('Raw records:', raw.length);
console.log('Unique placeIds:', seenPlaceIds.size);
console.log('Null imageUrl (skipped):', nullImageCount);
console.log('Usable lh3.googleusercontent.com photo rows:', rows.length);
if (otherHosts.size > 0) {
  console.log('Other image hosts seen (NOT included, not allow-listed):');
  for (const [host, count] of otherHosts) console.log(`  ${host}: ${count}`);
}
console.log('Chunks written:', writtenFiles.length);
for (const f of writtenFiles) console.log(' -', path.relative(path.join(__dirname, '..'), f));
